"""Built-in, non-agent workflow steps. Each returns a verdict (`done` unless the state lists
its own `verdicts`), or raises → `error`."""

import re
from collections.abc import Awaitable, Callable
from dataclasses import dataclass
from pathlib import Path

import httpx

from . import gitops
from .db import Project, WorkItem
from .github import GitHub
from .workflow import DONE


@dataclass
class ActionContext:
    gh: GitHub
    project: Project
    item: WorkItem
    cwd: Path
    artifacts: dict[str, str]  # latest content per artifact name
    report: str = ""  # becomes an artifact named after the action


Action = Callable[[ActionContext], Awaitable[str]]

CONFLICT = "conflict"
MERGED = "merged"
MANUAL = "manual"
# GitHub won't merge: branch protection, conflicts, the head moved on, or no permission.
MERGE_REFUSED = {403, 405, 409, 422}
# Repository setting that allows each merge method, in order of preference.
MERGE_METHODS = {"squash": "allow_squash_merge", "merge": "allow_merge_commit", "rebase": "allow_rebase_merge"}


async def sync_base(ctx: ActionContext) -> str:
    """Merge the latest base branch into the item's branch, so parallel stories build on each
    other's merged work and PRs don't conflict. Merges rather than rebases: reviewed history
    stays intact. On conflict the merge is left in progress for the implementer to resolve
    (`conflict` verdict); the conflicted files go into the `sync_base` artifact."""
    item, cwd = ctx.item, ctx.cwd
    base = f"origin/{item.base_branch}"
    if gitops.merge_in_progress(cwd):
        if conflicts := await gitops.unmerged_files(cwd):
            ctx.report = _conflict_report(base, conflicts, still=True)
            return CONFLICT
        await gitops.commit_all_if_dirty(cwd, f"Merge {base} into {item.branch}")
    await gitops.commit_all_if_dirty(cwd, f"{item.title} (uncommitted agent changes)")
    await gitops.fetch(cwd, item.base_branch, token=await ctx.gh.git_token())
    if await gitops.is_ancestor(cwd, base):
        ctx.report = f"Up to date with {base}."
        return DONE
    conflicts = await gitops.merge(cwd, base, f"Merge {base} into {item.branch}")
    if conflicts:
        ctx.report = _conflict_report(base, conflicts)
        return CONFLICT
    ctx.report = f"Merged {base} cleanly: {(await gitops.head_sha(cwd))[:12]}."
    return DONE


def _conflict_report(base: str, files: list[str], still: bool = False) -> str:
    listing = "\n".join(f"- {f}" for f in files)
    return (
        f"{'The merge of ' + base + ' still has' if still else 'Merging ' + base + ' into this branch left'} "
        f"conflicts in:\n{listing}\n\n"
        "A merge is in progress in the workspace. Resolve each conflict so that both this task's "
        f"changes and the intent of the changes on {base} survive (read `git log {base}` for what "
        "they did), run the tests, then `git add` the files and `git commit` to conclude the merge. "
        "Do not abort the merge, rebase or reset."
    )


async def open_pr(ctx: ActionContext) -> str:
    """Push the item's branch and open its PR (or reuse the open one; pushing updates it)."""
    item, repo = ctx.item, ctx.project.repo
    await gitops.commit_all_if_dirty(ctx.cwd, f"{item.title} (uncommitted agent changes)")
    if await gitops.commits_ahead(ctx.cwd, item.base_branch) == 0:
        raise RuntimeError("nothing to publish: the branch has no commits")
    await gitops.push(ctx.cwd, item.branch, token=await ctx.gh.git_token())
    item.head_sha = await gitops.head_sha(ctx.cwd)

    pr = await ctx.gh.find_open_pr(repo, item.branch)
    if pr is None:
        parts = []
        if issue := item.source.get("issue"):
            parts.append(f"Closes #{issue}")
        for name in ("planner", "implementer", "reviewer"):
            if ctx.artifacts.get(name):
                parts.append(f"## {name.capitalize()}\n\n{ctx.artifacts[name]}")
        parts.append("---\n🤖 Generated by agent-harness with [Claude Code](https://claude.com/claude-code)")
        body = "\n\n".join(parts)
        pr = await ctx.gh.create_pr(repo, head=item.branch, base=item.base_branch, title=item.title, body=body)
    item.pr_url = pr["html_url"]
    return DONE


async def merge_pr(ctx: ActionContext) -> str:
    """Merge the item's PR if the project has automerge on: by now it was reviewed and CI
    passed. Otherwise, or when GitHub refuses, the PR waits for a human (`manual`); GitHub's
    reason goes into the `merge` artifact. Merges only the head CI checked."""
    if not ctx.project.auto_merge:
        return MANUAL
    match = re.search(r"/pull/(\d+)", ctx.item.pr_url or "")
    if not match:
        raise RuntimeError("the item has no PR to merge")
    repo, number = ctx.project.repo, int(match[1])
    repo_info = await ctx.gh.get_repo(repo)
    method = next((m for m, allowed in MERGE_METHODS.items() if repo_info.get(allowed, True)), "merge")
    try:
        await ctx.gh.merge_pr(repo, number, method=method, sha=ctx.item.head_sha)
    except httpx.HTTPStatusError as e:
        if e.response.status_code not in MERGE_REFUSED:
            raise
        try:
            reason = e.response.json().get("message") or e.response.text
        except ValueError:
            reason = e.response.text
        ctx.report = f"Automerge: GitHub refused to merge PR #{number} ({e.response.status_code}): {reason}"
        return MANUAL
    ctx.report = f"Automerge: merged PR #{number} ({method})."
    return MERGED


ACTIONS: dict[str, Action] = {"open_pr": open_pr, "sync_base": sync_base, "merge": merge_pr}
